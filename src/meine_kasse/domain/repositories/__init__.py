"""Schnittstellen für den Datenzugriff. Die Implementierung liegt in der Infrastruktur."""

from collections.abc import Mapping, Sequence
from types import TracebackType
from typing import Protocol, Self

from meine_kasse.domain.entities import (
    Account,
    AccountOpeningBalance,
    AuditEntry,
    Booking,
    BookingControl,
    ClosureReopening,
    CostCenter,
    CostCenterPlan,
    MonthlyActual,
    MonthlyPlan,
    PeriodClosure,
    User,
    YearClosure,
)


class UserRepository(Protocol):
    def add(self, user: User) -> None: ...

    def update(self, user: User) -> None: ...

    def get(self, user_id: str) -> User | None: ...

    def get_by_name(self, name: str) -> User | None:
        """Sucht einen Anwender ohne Beachtung der Groß-/Kleinschreibung."""
        ...

    def list_all(self) -> Sequence[User]: ...

    def count(self) -> int: ...


class CostCenterRepository(Protocol):
    def add(self, cost_center: CostCenter) -> None: ...

    def update(self, cost_center: CostCenter) -> None: ...

    def get(self, cost_center_id: str) -> CostCenter | None: ...

    def get_by_number(self, number: str) -> CostCenter | None: ...

    def list_all(self) -> Sequence[CostCenter]: ...


class AccountRepository(Protocol):
    def add(self, account: Account) -> None: ...

    def update(self, account: Account) -> None: ...

    def get(self, account_id: str) -> Account | None: ...

    def get_by_number(self, number: str) -> Account | None: ...

    def list_all(self) -> Sequence[Account]: ...


class AuditRepository(Protocol):
    def add(self, entry: AuditEntry) -> None: ...


class BookingControlRepository(Protocol):
    def get_active(self) -> BookingControl | None: ...

    def add(self, control: BookingControl) -> None: ...

    def update(self, control: BookingControl) -> None: ...


class ClosureRepository(Protocol):
    def closed_months(self) -> set[tuple[int, int]]: ...

    def closed_years(self) -> set[int]: ...

    def list_months(self) -> Sequence[PeriodClosure]: ...

    def list_years(self) -> Sequence[YearClosure]: ...

    def add_month(self, closure: PeriodClosure) -> None: ...

    def add_year(self, closure: YearClosure) -> None: ...

    def delete_month(self, year: int, month: int) -> None: ...

    def delete_year(self, year: int) -> None: ...

    def add_reopening(self, reopening: ClosureReopening) -> None: ...

    def list_reopenings(self) -> Sequence[ClosureReopening]: ...


class BookingRepository(Protocol):
    def add(self, booking: Booking) -> None: ...

    def update(self, booking: Booking) -> None:
        """Ersetzt Kopfdaten und beide Buchungsstellen."""
        ...

    def delete(self, booking_id: str) -> None: ...

    def get(self, booking_id: str) -> Booking | None: ...

    def has_reversal(self, booking_id: str) -> bool: ...

    def list_by_transfer(self, transfer_id: str) -> Sequence[Booking]: ...

    def list_filtered(self, year: int | None, month: int | None) -> Sequence[Booking]: ...

    def account_balance_cents(self, account_id: str) -> int:
        """Bewegung = Haben - Soll über alle Buchungen des Kontos (ohne Vortrag)."""
        ...

    def account_year_movements(self) -> Mapping[tuple[str, int], int]:
        """Bewegung (Haben - Soll) je (Konto, Geschäftsjahr); Schlüssel nur, wenn gebucht wurde."""
        ...

    def cost_center_actual_totals(self) -> Mapping[tuple[str, int, int], tuple[int, int]]:
        """Soll- und Haben-Summe je (Kostenstelle, Jahr, Monat) aus Ist-Buchungen."""
        ...

    def budget_transfer_totals(self) -> Mapping[tuple[str, int], int]:
        """Summe der Ansatzumbuchungen je (Kostenstelle, Jahr)."""
        ...


class OpeningBalanceRepository(Protocol):
    def get(self, account_id: str) -> AccountOpeningBalance | None: ...

    def list_all(self) -> Sequence[AccountOpeningBalance]: ...

    def save(self, opening: AccountOpeningBalance) -> None:
        """Legt den Vortrag des Kontos an oder ersetzt ihn (auch das Jahr)."""
        ...

    def delete(self, account_id: str) -> None: ...


class PlanRepository(Protocol):
    def get_plan(self, cost_center_id: str, year: int) -> CostCenterPlan | None: ...

    def save_plan(self, plan: CostCenterPlan) -> None: ...

    def list_plans(self) -> Sequence[CostCenterPlan]: ...

    def plans_of_cost_center(self, cost_center_id: str) -> Sequence[CostCenterPlan]:
        """Alle Jahrespläne einer Kostenstelle, aufsteigend nach Jahr."""
        ...

    def monthly_plans(self, cost_center_id: str, year: int) -> Sequence[MonthlyPlan]: ...

    def monthly_plans_for_month(self, year: int, month: int) -> Sequence[tuple[str, MonthlyPlan]]:
        """Monatsplanwerte aller Kostenstellen eines Monats als (Kostenstelle, Plan)."""
        ...

    def save_monthly_plan(self, plan: MonthlyPlan) -> None: ...

    def get_actual(self, cost_center_id: str, year: int, month: int) -> MonthlyActual | None: ...

    def save_actual(self, actual: MonthlyActual) -> None: ...

    def actuals_for_year(self, cost_center_id: str, year: int) -> Sequence[MonthlyActual]: ...

    def list_actuals(self) -> Sequence[MonthlyActual]: ...

    def delete_actual(self, actual_id: str) -> None: ...


class UserSettingRepository(Protocol):
    """Anwendereinstellungen als JSON-Text je Anwender und Schlüssel."""

    def get(self, user_id: str, key: str) -> str | None: ...

    def save(self, user_id: str, key: str, value_json: str) -> None: ...

    def delete(self, user_id: str, key: str) -> None: ...


class UnitOfWork(Protocol):
    """Eine Transaktion. Ohne `commit()` wird beim Verlassen zurückgerollt."""

    @property
    def users(self) -> UserRepository: ...

    @property
    def user_settings(self) -> UserSettingRepository: ...

    @property
    def cost_centers(self) -> CostCenterRepository: ...

    @property
    def accounts(self) -> AccountRepository: ...

    @property
    def audit(self) -> AuditRepository: ...

    @property
    def booking_control(self) -> BookingControlRepository: ...

    @property
    def closures(self) -> ClosureRepository: ...

    @property
    def bookings(self) -> BookingRepository: ...

    @property
    def opening_balances(self) -> OpeningBalanceRepository: ...

    @property
    def plans(self) -> PlanRepository: ...

    def __enter__(self) -> Self: ...

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        traceback: TracebackType | None,
    ) -> None: ...

    def commit(self) -> None: ...
